namespace Intelligence.TradeSystem.Domain;

/// <summary>
/// Категория торгового рынка на бирже Bybit.
/// Определяет тип инструмента и механику расчёта PnL.
/// </summary>
public enum MarketCategory
{
    /// <summary>
    /// Спотовый рынок. Торговля реальным активом с немедленным расчётом.
    /// PnL рассчитывается в базовой валюте пары.
    /// </summary>
    Spot,

    /// <summary>
    /// Линейный бессрочный контракт (USDT-маржинальный).
    /// Котируется и рассчитывается в USDT, что упрощает управление рисками.
    /// </summary>
    Linear,

    /// <summary>
    /// Инверсный бессрочный контракт (монетно-маржинальный).
    /// Котируется в USD, но маржа и PnL рассчитываются в базовой криптовалюте (например, BTC).
    /// </summary>
    Inverse
}
