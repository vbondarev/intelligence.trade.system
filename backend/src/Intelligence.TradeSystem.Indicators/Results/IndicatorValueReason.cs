namespace Intelligence.TradeSystem.Indicators.Results;

/// <summary>
/// Описывает причину, по которой значение индикатора является fallback или недоступным.
/// </summary>
/// <remarks>
/// Используется совместно с <see cref="IndicatorValue"/> для явного указания семантики результата.
/// <para>
/// Значение <see cref="None"/> означает штатный расчёт без fallback.
/// Все остальные значения указывают на нестандартную ситуацию, которая повлияла на результат.
/// </para>
/// </remarks>
public enum IndicatorValueReason
{
    /// <summary>
    /// Значение рассчитано штатно, без fallback. Используется только с <see cref="IndicatorValue.Available"/>.
    /// </summary>
    None = 0,

    /// <summary>
    /// Входная коллекция была пустой. Значение индикатора недоступно.
    /// </summary>
    EmptyInput = 1,

    /// <summary>
    /// Данных недостаточно для полноценного расчёта индикатора.
    /// Например, количество свечей меньше минимально необходимого.
    /// </summary>
    InsufficientData = 2,

    /// <summary>
    /// Значение рассчитано по неполному окну как fallback.
    /// Например, SMA или EMA посчитаны по меньшему количеству элементов, чем заданный период.
    /// </summary>
    PartialWindow = 3,

    /// <summary>
    /// Входные данные некорректны с доменной точки зрения.
    /// Например, рассинхронизация OHLC-массивов или отрицательные значения там, где они недопустимы.
    /// </summary>
    InvalidInput = 4,
}
