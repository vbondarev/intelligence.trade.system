namespace Intelligence.TradeSystem.Application.Realtime.Observations;

/// <summary>
/// Классификация сообщения приватного потока позиций адаптером биржи.
/// </summary>
/// <remarks>
/// Классификация не применяет изменения жизненного цикла: порядок относительно сохранённых
/// курсоров и подтверждение закрытия определяет прикладной слой.
/// </remarks>
public enum PrivatePositionObservationKind
{
    /// <summary>Открытая позиция с подтверждёнными идентичностью, направлением и активом расчёта.</summary>
    Open = 1,

    /// <summary>
    /// Нулевой размер позиции. Не означает закрытия: lifecycle закрывается только после
    /// подтверждения полноты наблюдения.
    /// </summary>
    PotentialClose = 2,

    /// <summary>Повтор уже полученного этим провайдером сообщения без изменений.</summary>
    Duplicate = 3,

    /// <summary>Наблюдение вне поддерживаемой области (категория или актив расчёта).</summary>
    Unsupported = 4,

    /// <summary>
    /// Наблюдение нельзя достоверно интерпретировать; актуальное состояние требует REST-сверки.
    /// </summary>
    Ambiguous = 5,
}
