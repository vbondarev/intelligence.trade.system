namespace Intelligence.TradeSystem.Application.Realtime.Observations;

/// <summary>
/// Классификация сообщения приватного потока кошелька адаптером биржи.
/// </summary>
/// <remarks>
/// Ни одно значение не означает полного снимка аккаунта: Bybit не гарантирует, что сообщение
/// кошелька содержит все типы аккаунта и монеты. Полное состояние подтверждает только REST-сверка.
/// </remarks>
public enum PrivateWalletObservationKind
{
    /// <summary>
    /// Частичное потоковое наблюдение: содержит хотя бы один применимый баланс поддерживаемого
    /// типа аккаунта. Отсутствие других типов аккаунта или монет не означает их нулевого баланса.
    /// </summary>
    PartialUpdate = 1,

    /// <summary>
    /// Сообщение не содержит применимых балансов (пустое, только неподдерживаемые типы аккаунта
    /// или записи без значений). Не подтверждает нулевой баланс; актуальное состояние требует
    /// REST-сверки.
    /// </summary>
    Unconfirmed = 2,
}
