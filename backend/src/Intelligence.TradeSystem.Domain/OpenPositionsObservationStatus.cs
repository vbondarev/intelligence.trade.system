namespace Intelligence.TradeSystem.Domain;

/// <summary>
/// Достоверность и полнота результата наблюдения открытых позиций, полученного от биржи.
/// </summary>
/// <remarks>
/// Ключевой архитектурный инвариант:
/// <c>успешно получено 0 позиций</c> != <c>не удалось получить позиции</c>.
/// Только <see cref="Complete"/> может служить основанием считать ранее открытую
/// позицию отсутствующей (закрытой) в пределах области (scope) наблюдения.
/// </remarks>
public enum OpenPositionsObservationStatus
{
    /// <summary>
    /// Система уверена, что получила полный набор позиций для запрошенной области (scope).
    /// Пустой список в этом статусе — валидный успешный снимок отсутствия позиций.
    /// </summary>
    Complete = 0,

    /// <summary>
    /// Получена только часть достоверных данных, либо полнота набора не гарантируется.
    /// Достоверно наблюдаемые позиции можно обновить, но отсутствующие в наборе —
    /// нельзя считать закрытыми.
    /// </summary>
    Partial = 1,

    /// <summary>
    /// Состояние открытых позиций получить не удалось. Пустой список позиций в этом
    /// статусе не означает отсутствие открытых позиций — ни одна ранее наблюдавшаяся
    /// позиция не должна становиться закрытой на основании этого результата.
    /// </summary>
    Failed = 2,
}
