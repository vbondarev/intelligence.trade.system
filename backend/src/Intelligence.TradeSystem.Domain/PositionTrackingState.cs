namespace Intelligence.TradeSystem.Domain;

/// <summary>
/// Долговременное состояние жизненного цикла бизнес-позиции.
/// Не путать с <see cref="PositionStatus"/>, который описывает биржевое (Bybit-side)
/// состояние конкретного наблюдения, а не жизненный цикл бизнес-позиции.
/// </summary>
public enum PositionTrackingState
{
    /// <summary>
    /// Последнее достоверное наблюдение подтверждает существование позиции.
    /// </summary>
    Active = 0,

    /// <summary>
    /// Последняя попытка получить состояние позиции не дала достаточных данных.
    /// Это не означает, что позиция закрыта.
    /// </summary>
    Unknown = 1,

    /// <summary>
    /// Последнее подтверждённое наблюдение слишком старое относительно заданного
    /// допустимого возраста данных (<c>staleAfter</c>).
    /// </summary>
    Stale = 2,

    /// <summary>
    /// Позиция достоверно отсутствует в полном (<see cref="OpenPositionsObservationStatus.Complete"/>)
    /// снимке соответствующей области (scope).
    /// </summary>
    Closed = 3,
}
